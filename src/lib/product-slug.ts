export function slugifyProductValue(value: string | null | undefined) {
  return (value ?? "")
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .replace(/-{2,}/g, "-");
}

export function normalizeProductSlug(slug: string | null | undefined, fallbackName?: string | null) {
  return slugifyProductValue(slug) || slugifyProductValue(fallbackName);
}
